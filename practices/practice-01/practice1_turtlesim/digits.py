def symbol_code(symbol: str) -> int:
    """Код символа: 0-9 для цифр, 10-35 для букв A-Z (как int(ch, 36))."""
    return int(symbol, 36)


# Все символы, ключ - код из symbol_code
GLYPHS: Dict[int, List[Point]] = {
    symbol_code(ch): pts for ch, pts in {**_DIGITS, **_LETTERS}.items()
}
# Старое имя, чтобы прежний код не сломался
DIGIT_POLYLINES = GLYPHS


def digit_path(
    digit: int, origin_x: float, origin_y: float, width: float, height: float
) -> List[Point]:
    """Точки символа в координатах turtlesim.

    digit - код символа (0-9 цифры, 10-35 буквы A-Z, см. symbol_code).
    origin_x, origin_y - левый нижний угол символа, width и height - его размеры.
    """
    return [
        (origin_x + u * width, origin_y + v * height) for u, v in GLYPHS[digit]
    ]


# ---------------------------------------------------------------------------
# Раскладка текста по окну turtlesim
# ---------------------------------------------------------------------------

WINDOW = 11.0889  # сторона окна turtlesim в единицах
MARGIN = 0.5  # отступ от края окна, чтобы линии не упирались в границу
MAX_SYMBOL_WIDTH = 3.0  # короткие надписи не растягиваем шире этого
MAX_SYMBOL_HEIGHT = 6.0
ASPECT = 2.5  # высота символа / ширина символа
GAP_RATIO = 0.33  # зазор между символами в долях ширины символа
MAX_SYMBOLS = 8  # при большем числе символов они становятся слишком мелкими
ALLOWED = set(_DIGITS) | set(_LETTERS) | {" "}


@dataclass(frozen=True)
class GlyphCell:
    """Где и каким размером рисуется один символ надписи."""

    symbol: str  # сам символ; пробел ничего не рисует
    code: int  # код для параметра digit узла; для пробела -1
    origin_x: float
    origin_y: float
    width: float
    height: float


def layout_text(text: str) -> List[GlyphCell]:
    """Раскладывает надпись по окну: символы одного размера, ряд по центру.

    text - цифры, латинские буквы (регистр не важен) и пробелы, например
    "8642", "HELLO" или "GO AWAY". Пробел занимает место, но ничего не рисует.
    Размер символов уменьшается с ростом их числа, для 1-2 символов остаётся
    максимальным (3 x 6).
    """
    text = text.upper()
    bad = sorted(set(text) - ALLOWED)
    if bad or not text.strip():
        raise ValueError(
            "допустимы цифры 0-9, латинские буквы и пробел, "
            f"получено {text!r}" + (f" (недопустимо: {bad})" if bad else "")
        )
    count = len(text)
    if count > MAX_SYMBOLS:
        raise ValueError(f"не больше {MAX_SYMBOLS} символов, получено {count}")

    usable = WINDOW - 2 * MARGIN
    # count символов и (count - 1) зазоров должны уместиться в usable
    width = min(MAX_SYMBOL_WIDTH, usable / (count + (count - 1) * GAP_RATIO))
    height = min(MAX_SYMBOL_HEIGHT, ASPECT * width)
    gap = GAP_RATIO * width

    total_width = count * width + (count - 1) * gap
    start_x = (WINDOW - total_width) / 2  # ряд по центру по горизонтали
    origin_y = (WINDOW - height) / 2  # и по вертикали

    return [
        GlyphCell(
            ch,
            -1 if ch == " " else symbol_code(ch),
            start_x + i * (width + gap),
            origin_y,
            width,
            height,
        )
        for i, ch in enumerate(text)
    ]


